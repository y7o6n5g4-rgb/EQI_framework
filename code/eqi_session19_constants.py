import mpmath
from mpmath import mp
import numpy as np

# =======================================================================
# 1. mpmath 초정밀도 버전 (dps=400, True Zero 록온용)
# =======================================================================
mp.dps = 400

class EQI_Constants_MP:
    # -------------------------------------------------------------------
    # [기존 공통 상수 유지]
    # -------------------------------------------------------------------
    PHI = (mp.sqrt(mp.mpf('5.0')) + mp.mpf('1.0')) / mp.mpf('2.0')
    D1 = mp.power(PHI, -1.5)           # 수축, 수렴, 닫힌 계
    D2 = mp.power(PHI, 1.5)            # 팽창, 발산, 열린 계
    W_H = mp.power(PHI, -2.0)          # 진공 전기 텐션, 1/MAXWELL 무게중심 기저
    W_L = mp.power(PHI, -1.0)          # 진공 자기 텐션
    
    GAP = mp.ln(mp.mpf('25.0')) / mp.mpf('100.0') # 유클리드 점의 에일리어싱 텐션 누수
    
    MAXWELL_EQI = mp.mpf('2.0')        # 순수 위상 MAXWELL
    MAXWELL_SI = mp.mpf('2.0') - mp.mpf('4.0') * GAP # 4D 시공간 투영 MAXWELL
    MAXWELL_REAL = mp.mpf('1.8731137721991709') # SI 단위계 실측 MAXWELL
    
    c_EQI = mp.sqrt(PHI)               # 광속의 위상동형 (Monster Identity)
    ETA_EQI = mp.mpf('1.0') - mp.power(PHI, -3.0) # 순수 볼츠만 파단비 기반 카르노 효율

    # -------------------------------------------------------------------
    # [세션 19 신규 확립 공리 및 상수]
    # -------------------------------------------------------------------
    # 1. 진공/물질 채널 디코딩 차수 분기 (v89.0 & v87.0)
    N_BBH = mp.mpf('0.25')             # 진공 채널: 4D 시공간의 1D 정수 투영비
    N_BNS = mp.power(PHI, -5.0)        # 물질 채널: W_H^2 * W_L 힉스 매듭 프랙탈 붕괴
    
    # 2. 우로보로스 임계 거동 (v93.0)
    N_SEED = (mp.mpf('3.0') * mp.ln(PHI) - mp.mpf('1.0')) / GAP # 씨앗이 D2 텐션에 도달하는 임계점
    N_PHI = mp.ln(PHI) / GAP           # e^(n*GAP)가 φ에 도달하는 우주 팽창 임계점
    
    # 3. 인식론-열역학 True Zero 동기화 (v93.0)
    THERMO_RUPTURE = mp.mpf('3.0') * mp.ln(PHI) # 우주의 열역학적 온도 파단비 (ln(D2/D1))
    EQI_OUROBOROS_BASE = mp.mpf('1.0') + GAP    # 관측 개입 시 열려버리는 인식론적 Unity
    D2_D1_RATIO = mp.power(PHI, 3.0)            # 볼츠만 파단비 (A-B 위상 편차)


# =======================================================================
# 2. numpy 표준 정밀도 버전 (배열 연산 및 고속 시뮬레이션용)
# =======================================================================
class EQI_Constants_NP:
    # -------------------------------------------------------------------
    # [기존 공통 상수 유지]
    # -------------------------------------------------------------------
    PHI = (np.sqrt(5.0) + 1.0) / 2.0
    D1 = PHI**(-1.5)
    D2 = PHI**(1.5)
    W_H = PHI**(-2.0)
    W_L = PHI**(-1.0)
    
    GAP = np.log(25.0) / 100.0
    
    MAXWELL_EQI = 2.0
    MAXWELL_SI = 2.0 - 4.0 * GAP
    MAXWELL_REAL = 1.8731137721991709
    
    c_EQI = np.sqrt(PHI)
    ETA_EQI = 1.0 - PHI**(-3.0)

    # -------------------------------------------------------------------
    # [세션 19 신규 확립 공리 및 상수]
    # -------------------------------------------------------------------
    N_BBH = 0.25
    N_BNS = PHI**(-5.0)
    
    N_SEED = (3.0 * np.log(PHI) - 1.0) / GAP
    N_PHI = np.log(PHI) / GAP
    
    THERMO_RUPTURE = 3.0 * np.log(PHI)
    EQI_OUROBOROS_BASE = 1.0 + GAP
    D2_D1_RATIO = PHI**3.0