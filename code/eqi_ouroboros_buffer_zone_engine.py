import mpmath
from mpmath import mp

# 400자리 초정밀도 절대 록온
mp.dps = 400

def get_phinary_expansion(value, max_terms=10):
    phi = (mp.sqrt(5) + mp.mpf('1.0')) / mp.mpf('2.0')
    rem = value
    indices = []
    for n in range(0, 150): # 0부터 시작 (phi^0 = 1.0 포함)
        term = mp.power(phi, -n)
        if term <= rem:
            indices.append(n)
            rem -= term
            if len(indices) >= max_terms or rem < 1e-100:
                break
    return indices, rem

